// 공지사항(/notice). 최신 글이 위로 오게 넣는다. 사실만 적는다.
// 11-01 일반 회사 게시판처럼 고객에게 알릴 내용만 짧게. 내부 작업 기록(배경, 목표, 캐릭터 공개)은 뺐다. 날짜는 바꾸지 않는다.
// date는 그 내용이 실제로 적용된 날이다(커밋 기록 기준). 제목은 "N차 리뉴얼" 대신 그때 새로 더한 것을 쓴다(10-30 사용자: 자주 바꾼 느낌이 안 들게).
export interface NoticeSection {
  h: string;
  p?: string[];
  list?: string[];
}

export interface Notice {
  id: string;
  /** YYYY-MM-DD */
  date: string;
  title: string;
  /** 목록과 검색 설명에 쓰는 한 줄 요약 */
  summary: string;
  sections: NoticeSection[];
  /** 그때 첫 화면 전체를 한 장으로 찍은 캡처. w, h는 원본 픽셀 크기 */
  image?: { src: string; alt: string; note?: string; w: number; h: number };
  /** 11-08 이벤트 말머리. 시작은 date, 끝나는 날(YYYY-MM-DD, 그날까지)을 둔다. 목록과 글 머리에 "이벤트"와 진행 상태를 붙인다 */
  event?: { end: string };
}

/** 이벤트 진행 상태. 정적 내보내기라 빌드 시점 기준이다(배포할 때마다 다시 계산된다) */
export function eventStatus(n: Notice): "진행 중" | "마감" | null {
  if (!n.event) return null;
  return new Date() > new Date(`${n.event.end}T23:59:59+09:00`) ? "마감" : "진행 중";
}

